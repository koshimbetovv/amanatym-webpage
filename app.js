const languageLabels = {
  en: "EN",
  tr: "TR",
  tkm: "TKM",
  ru: "RU",
};

const picker = document.querySelector(".language-picker");
const languageButton = document.querySelector(".language-button");
const currentLanguage = document.querySelector(".current-language");
const languageOptions = document.querySelectorAll("[data-lang]");
const footerLanguages = document.querySelectorAll("[data-footer-lang]");
const menuButton = document.querySelector(".menu-button");
const header = document.querySelector(".site-header");
const mobileLinks = document.querySelectorAll(".mobile-nav a");
const faqButtons = document.querySelectorAll(".faq-item button");
const storeButtons = document.querySelectorAll("[data-store]");
const toast = document.querySelector(".toast");
let toastTimer;

function valueAtPath(object, path) {
  return path.split(".").reduce((value, key) => value?.[key], object);
}

function setLanguage(language) {
  const selected = translations[language] ? language : "en";
  const copy = translations[selected];

  document.documentElement.lang = selected === "tkm" ? "tk" : selected;
  document.title = copy.meta.title;
  document.querySelector('meta[name="description"]').setAttribute("content", copy.meta.description);
  currentLanguage.textContent = languageLabels[selected];

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = valueAtPath(copy, element.dataset.i18n);
    if (value) element.textContent = value;
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    const value = valueAtPath(copy, element.dataset.i18nAlt);
    if (value) element.setAttribute("alt", value);
  });

  languageOptions.forEach((option) => {
    option.setAttribute("aria-selected", String(option.dataset.lang === selected));
  });

  localStorage.setItem("amanatym-language", selected);
  closeLanguagePicker();
}

function closeLanguagePicker() {
  picker.classList.remove("open");
  languageButton.setAttribute("aria-expanded", "false");
}

function closeMobileMenu() {
  header.classList.remove("mobile-open");
  document.body.classList.remove("menu-open");
  menuButton.setAttribute("aria-expanded", "false");
}

languageButton.addEventListener("click", () => {
  const isOpen = picker.classList.toggle("open");
  languageButton.setAttribute("aria-expanded", String(isOpen));
});

languageOptions.forEach((option) => {
  option.addEventListener("click", () => setLanguage(option.dataset.lang));
});

footerLanguages.forEach((option) => {
  option.addEventListener("click", () => {
    setLanguage(option.dataset.footerLang);
    window.scrollTo({ top: 0, behavior: "smooth" });
  });
});

document.addEventListener("click", (event) => {
  if (!picker.contains(event.target)) closeLanguagePicker();
});

menuButton.addEventListener("click", () => {
  const isOpen = header.classList.toggle("mobile-open");
  document.body.classList.toggle("menu-open", isOpen);
  menuButton.setAttribute("aria-expanded", String(isOpen));
});

mobileLinks.forEach((link) => link.addEventListener("click", closeMobileMenu));

faqButtons.forEach((button) => {
  button.addEventListener("click", () => {
    const item = button.closest(".faq-item");
    const willOpen = !item.classList.contains("open");

    document.querySelectorAll(".faq-item").forEach((faqItem) => {
      faqItem.classList.remove("open");
      faqItem.querySelector("button").setAttribute("aria-expanded", "false");
    });

    if (willOpen) {
      item.classList.add("open");
      button.setAttribute("aria-expanded", "true");
    }
  });
});

storeButtons.forEach((button) => {
  button.addEventListener("click", (event) => {
    event.preventDefault();
    toast.classList.add("show");
    clearTimeout(toastTimer);
    toastTimer = setTimeout(() => toast.classList.remove("show"), 3000);
  });
});

document.addEventListener("keydown", (event) => {
  if (event.key !== "Escape") return;
  closeLanguagePicker();
  closeMobileMenu();
});

document.getElementById("year").textContent = new Date().getFullYear();

const browserLanguage = navigator.language.toLowerCase();
const requestedLanguage = new URLSearchParams(window.location.search).get("lang");
const initialLanguage =
  (translations[requestedLanguage] && requestedLanguage) ||
  localStorage.getItem("amanatym-language") ||
  (browserLanguage.startsWith("tr")
    ? "tr"
    : browserLanguage.startsWith("ru")
      ? "ru"
      : browserLanguage.startsWith("tk")
        ? "tkm"
        : "en");

setLanguage(initialLanguage);
